import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => fs.readFileSync(path.join(root, 'Shared', name), 'utf8');
const plain = text => text.replace(/^import .*?;\s*$/gm, '').replace(/^export /gm, '');
const core = ['language.js', 'model.js', 'vocabulary.js'].map(n => plain(read(n))).join('\n');
const facade = `
function mobileCall(json) {
  try {
    const r = JSON.parse(json), knowledge = { terms: r.terms || [] };
    let value;
    switch (r.operation) {
      case 'command': value = commandFrom(r.text, knowledge); break;
      case 'search': value = searchPoints(r.points, r.text, knowledge); break;
      case 'spoken': value = spokenName(r.text, knowledge.terms); break;
      case 'terms': value = effectiveTerms(knowledge.terms); break;
      case 'termKey': value = languageKey(r.text); break;
      case 'validateTerms':
        value = parseVocabularyFile(JSON.stringify({format:'bacsolution-io-vocabulary',version:1,terms:r.terms})); break;
      default: throw new Error('Unbekannte lokale Anfrage.');
    }
    return JSON.stringify({ok:true,value});
  } catch(error) { return JSON.stringify({ok:false,error:String(error.message || error)}); }
}
`;
fs.writeFileSync(path.join(root, 'Resources', 'LanguageCore.js'), '// Generated by scripts/bundle.mjs. Edit Shared sources.\n' + core + facade);
// callAsyncJavaScript receives request as a structured argument, never as source text.
fs.writeFileSync(path.join(root, 'Resources', 'ControllerBridge.js'), plain(read('protocol.js')) + '\nreturn JSON.stringify(await controllerTask(request));\n');
fs.writeFileSync(path.join(root, 'Resources', 'ControllerLogin.js'), plain(read('login.js')) + `
try { return JSON.stringify(await controllerLogin(request)); }
catch (error) { return JSON.stringify({state:'error', message:String(error.message || 'Controller-Anmeldung fehlgeschlagen.')}); }
`);
console.log('Native JavaScript-Ressourcen erstellt.');
